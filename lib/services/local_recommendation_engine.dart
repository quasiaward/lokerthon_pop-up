import 'recommendation_engine.dart';

/// 기기 안에서 도는 규칙 기반 추천 엔진.
///
/// 6개 질문의 답변마다 어울리는 다과에 가중치를 더하고, 총점이 가장 높은
/// 다과를 고른다. 가중치 값은 백엔드 프롬프트(`backend/ai/prompts.py`)에
/// 적혀 있던 "각 질문의 의미"를 그대로 옮긴 것이라, 나중에 OpenAI 추천으로
/// 바꿔도 결과 성향이 크게 달라지지 않는다.
///
/// 점수 기준
/// - Q4 식감 / Q5 계절 / Q6 문양 : 메뉴를 직접 가리키는 신호라 최대 4점
/// - Q1 기분 / Q2 날씨 / Q3 동행 : 분위기 신호라 최대 3점
class LocalRecommendationEngine implements RecommendationEngine {
  const LocalRecommendationEngine();

  @override
  Future<String> recommend(List<String> answers) async {
    return pick(answers);
  }

  /// 동기 버전. 테스트와 디버깅에서 쓰기 편하도록 열어 둔다.
  static String pick(List<String> answers) {
    final scores = <String, int>{for (final menu in dagwaMenus) menu: 0};

    for (final answer in answers) {
      final table = _scoreTable[answer.trim()];
      if (table == null) continue; // 건너뛴 질문이나 알 수 없는 답변은 무시
      table.forEach((menu, point) {
        scores[menu] = (scores[menu] ?? 0) + point;
      });
    }

    var best = dagwaMenus.first;
    var bestScore = -1;
    for (final menu in _tieBreakOrder(answers)) {
      final score = scores[menu] ?? 0;
      if (score > bestScore) {
        best = menu;
        bestScore = score;
      }
    }
    return best;
  }

  /// 답변 전체를 하나도 못 고른 경우(전부 건너뜀)에도 늘 같은 메뉴만 나오지
  /// 않도록, 답변 조합에서 만든 해시로 탐색 시작점을 돌린다.
  /// 같은 답변에는 늘 같은 결과가 나오므로 결과는 여전히 재현 가능하다.
  static List<String> _tieBreakOrder(List<String> answers) {
    var hash = 7;
    for (final answer in answers) {
      hash = (hash * 31 + answer.hashCode) & 0x7fffffff;
    }
    final offset = hash % dagwaMenus.length;
    return [...dagwaMenus.sublist(offset), ...dagwaMenus.sublist(0, offset)];
  }
}

